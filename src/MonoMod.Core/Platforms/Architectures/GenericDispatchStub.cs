    // The native stub a Mono shared generic body is detoured to. It looks the generic context (or the vtable of this) up in
    // the zero-terminated (key, entry) table behind tableSlot and jumps to the entry without touching any argument. On a miss,
    // it calls IntPtr resolver(cookie, key) with all argument registers saved, and jumps to what it returns. The key is still in
    // its register when jumping to an entry, so an entry may be the miss path. A null this has the key 0, which takes the miss path.
