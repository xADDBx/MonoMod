                    0xA8, 0xB0, 0xB8, 0x34),
                _ => throw new PlatformNotSupportedException($"Shared generic dispatch is not supported on {arch}"),
            };

            if (keyOnThis)
                thisKey.CopyTo(stub, 0);
            Unsafe.WriteUnaligned(ref stub[tableOffs], tableSlot);
            Unsafe.WriteUnaligned(ref stub[cookieOffs], cookie);
            Unsafe.WriteUnaligned(ref stub[resolverOffs], resolver);
            var memory = Shared.CreateSingleExecutableStub(system, stub);
            miss = (nint)memory.BaseAddress + missOffs;
            return memory;
        }

