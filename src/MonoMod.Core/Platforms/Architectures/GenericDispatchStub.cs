        {
            var (stub, thisKey, tableOffs, cookieOffs, resolverOffs, missOffs) = arch switch
            {
                // mov rax, rcx or rdi; test rax, rax; jz +3; mov rax, [rax]
                ArchitectureKind.x86_64 => (StubX64.ToArray(), new byte[] { 0x48, 0x89, PlatformDetection.OS.Is(OSKind.Windows) ? (byte)0xC8 : (byte)0xF8,
                    0x48, 0x85, 0xC0, 0x74, 0x03, 0x48, 0x8B, 0x00 }, 0x0D, 0x76, 0x89, 0x2D),
                // mov eax, [esp + 4]; test eax, eax; jz +2; mov eax, [eax]
